package provider

import (
	"context"
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/malico/docker-release/internal/docker"
)

type CaddyRoute struct {
	Host        string
	Path        string
	TLSCert     string
	TLSKey      string
	TLSRedirect bool
	Keepalive   int
	Affinity    string
}

func NewCaddyRoutes(configDir string, route CaddyRoute, dockerClient *docker.Client, serviceName, project string) *CaddyProvider {
	p := NewCaddy(configDir, dockerClient, serviceName, project)
	p.bundled = true
	p.route = route
	return p
}

func (p *CaddyProvider) generateBundledConfig(state *UpstreamState) error {
	p.stateFile = filepath.Join(p.configDir, state.Service+".upstreams")
	data, err := json.Marshal(caddyAddresses(state))
	if err != nil {
		return err
	}
	conf := renderCaddyBundledUpstream(state, p.stateFile, p.route)
	conf += renderCaddySites(state, p.route)
	if p.route.TLSCert != "" {
		cert, err := os.ReadFile(p.route.TLSCert)
		if err != nil {
			return err
		}
		key, err := os.ReadFile(p.route.TLSKey)
		if err != nil {
			return err
		}
		conf += fmt.Sprintf("# TLS %x\n", sha256.Sum256(append(cert, key...)))
	}
	p.pending = map[string][]byte{
		filepath.Join(p.configDir, state.Service+".caddy"):    []byte(conf),
		filepath.Join(p.configDir, state.Service+".location"): nil,
		p.stateFile: append([]byte("# Generated by docker-release\n"), data...),
	}
	if p.route.Host == "" && p.route.Path != "" {
		location := "# Generated by docker-release for Caddy\n" + renderCaddyHandler(state, p.route.Path)
		p.pending[filepath.Join(p.configDir, state.Service+".location")] = []byte(location)
	}
	return nil
}

func renderCaddySites(state *UpstreamState, route CaddyRoute) string {
	if route.Host == "" {
		return ""
	}
	var httpHosts, httpsHosts []string
	for _, host := range strings.Split(route.Host, ",") {
		host = strings.TrimSpace(host)
		httpHosts = append(httpHosts, "http://"+host)
		httpsHosts = append(httpsHosts, "https://"+host)
	}
	var b strings.Builder
	if route.TLSRedirect {
		fmt.Fprintf(&b, "\n%s {\n    redir https://{host}{uri} 308\n}\n", strings.Join(httpHosts, ", "))
	} else {
		httpsHosts = append(httpHosts, httpsHosts...)
	}
	fmt.Fprintf(&b, "\n%s {\n", strings.Join(httpsHosts, ", "))
	if route.TLSCert != "" {
		fmt.Fprintf(&b, "    tls %s %s\n", route.TLSCert, route.TLSKey)
	}
	b.WriteString(renderCaddyHandler(state, route.Path))
	if route.Path != "" && route.Path != "/" {
		b.WriteString("    handle {\n        respond 404\n    }\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func renderCaddyHandler(state *UpstreamState, path string) string {
	if path == "" || path == "/" {
		return fmt.Sprintf("    handle {\n        import %s_upstream\n    }\n", state.ResolveUpstreamName())
	}
	return fmt.Sprintf("    handle_path %s* {\n        import %s_upstream\n    }\n", path, state.ResolveUpstreamName())
}

func (p *CaddyProvider) RemoveStaleConfigs(ctx context.Context, active map[string]bool, canRemove func(string) bool) error {
	unlock, err := lockProxyConfigs(ctx, p.configDir, ".caddy.lock")
	if err != nil {
		return err
	}
	defer unlock()
	files, err := proxyConfigFilesByService(map[string][]string{p.configDir: {".caddy", ".location", ".upstreams"}})
	if err != nil {
		return err
	}
	changes := make(map[string][]byte)
	for service, paths := range files {
		if active[service] || !canRemove(service) {
			continue
		}
		for _, path := range paths {
			changes[path] = nil
		}
	}
	if len(changes) == 0 {
		return nil
	}
	return applyProxyConfigFiles(ctx, changes, p.reload)
}

func caddyAddresses(state *UpstreamState) []string {
	addresses := make([]string, 0, len(state.Servers))
	for _, server := range state.Servers {
		if server.Down || server.Backup {
			continue
		}
		weight := 1
		if state.Affinity == "" && server.Weight > 0 {
			weight = server.Weight
		}
		for range weight {
			addresses = append(addresses, server.Addr)
		}
	}
	return addresses
}

func renderCaddyBundledUpstream(state *UpstreamState, file string, route CaddyRoute) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by docker-release for Caddy\n(%s_upstream) {\n", state.ResolveUpstreamName())
	fmt.Fprintf(&b, "    reverse_proxy {\n        dynamic docker_release %q\n", file)
	// Replica counts and deployment affinity must not change the frontend config.
	switch route.Affinity {
	case "cookie":
		fmt.Fprintf(&b, "        lb_policy cookie %s\n", stickyCookieName(state))
	case "ip":
		b.WriteString("        lb_policy ip_hash\n")
	default:
		b.WriteString("        lb_policy round_robin\n")
	}
	if route.Keepalive >= 0 {
		b.WriteString("        transport http {\n")
		if route.Keepalive == 0 {
			b.WriteString("            keepalive off\n")
		} else {
			fmt.Fprintf(&b, "            keepalive_idle_conns_per_host %d\n", route.Keepalive)
		}
		b.WriteString("        }\n")
	}
	b.WriteString("    }\n}\n")
	return b.String()
}
