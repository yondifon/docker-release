package provider

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/malico/docker-release/internal/docker"
)

type NginxProvider struct {
	proxyName string
	configDir string
	routeDir  string
	route     NginxRoute

	docker      *docker.Client
	serviceName string
	project     string
	pending     map[string][]byte
}

type NginxRoute struct {
	Host        string
	Path        string
	SSLCert     string
	SSLKey      string
	SSLRedirect bool
}

func NewNginx(configDir, routeDir string, route NginxRoute, dockerClient *docker.Client, serviceName, project string) *NginxProvider {
	return &NginxProvider{
		proxyName:   "nginx",
		configDir:   configDir,
		routeDir:    routeDir,
		route:       route,
		docker:      dockerClient,
		serviceName: serviceName,
		project:     project,
	}
}

func (p *NginxProvider) GenerateConfig(ctx context.Context, state *UpstreamState) error {
	if err := state.Validate(); err != nil {
		return err
	}

	// Keep candidates off disk until the lock covers validation and reload.
	upstream := renderUpstream(state)
	if p.proxyName == "angie" {
		upstream = renderAngieUpstream(state)
	}
	p.pending = map[string][]byte{
		filepath.Join(p.configDir, state.Service+".conf"): []byte(upstream),
	}
	if p.routeDir == "" {
		return nil
	}
	serverPath := filepath.Join(p.routeDir, state.Service+".server")
	locationPath := filepath.Join(p.routeDir, state.Service+".location")
	p.pending[serverPath] = nil
	p.pending[locationPath] = nil
	if p.route.Host != "" {
		p.pending[serverPath] = []byte(renderNginxServer(state, p.route, p.proxyName))
	} else if p.route.Path != "" {
		p.pending[locationPath] = []byte(renderNginxLocation(state, p.route, p.proxyName))
	}
	return nil
}

func (p *NginxProvider) Reload(ctx context.Context) error {
	return p.applyConfigs(ctx, p.pending)
}

func (p *NginxProvider) reload(ctx context.Context) error {
	name := p.proxyName
	if strings.EqualFold(strings.TrimSpace(os.Getenv("DR_BUNDLED_PROXY")), name) {
		if _, err := os.Stat("/run/docker-release/" + name + ".started"); os.IsNotExist(err) {
			if bootstrap, _ := ctx.Value(proxyBootstrapKey{}).(bool); bootstrap {
				return nil
			}
			return fmt.Errorf("bundled %s is not ready; wait until the container is healthy before deploying", name)
		} else if err != nil {
			return err
		}
	}

	ctr, running, err := resolveProxyContainer(ctx, p.docker, p.project, p.serviceName, name)
	if err != nil {
		return fmt.Errorf("resolving %s container: %w", name, err)
	}

	if ctr.Labels["com.malico.docker-release.bundled-proxy"] != name && !matchesImage(ctr.Image, name, "alpine") {
		return fmt.Errorf("container %q has unexpected image %q (want %s or alpine-based)", ctr.ID[:12], ctr.Image, name)
	}

	if !running {
		return p.docker.Start(ctx, ctr.ID)
	}

	if err := p.docker.Exec(ctx, ctr.ID, []string{"/usr/sbin/" + name, "-t"}); err != nil {
		return fmt.Errorf("%s rejected config; check its config and certificates: %w", name, err)
	}
	reload := func() error {
		return p.docker.Exec(ctx, ctr.ID, []string{"/usr/sbin/" + name, "-s", "reload"})
	}
	if ctr.Labels["com.malico.docker-release.bundled-proxy"] == name {
		return confirmBundledReload(ctx, name, reload)
	}
	return reload()
}

func renderUpstream(state *UpstreamState) string {
	var b strings.Builder

	fmt.Fprintf(&b, "# Generated by docker-release\n")
	fmt.Fprintf(&b, "upstream %s_upstream {\n", state.ResolveUpstreamName())

	if state.Affinity == "ip" || state.Affinity == "cookie" {
		fmt.Fprintf(&b, "    ip_hash;\n")
	} else {
		fmt.Fprintf(&b, "    least_conn;\n")
	}

	for _, s := range state.Servers {
		if s.Backup && !supportsNginxBackup(state.Affinity) {
			continue
		}

		fmt.Fprintf(&b, "    server %s", s.Addr)

		if s.Down {
			fmt.Fprintf(&b, " down")
		} else if s.Backup {
			fmt.Fprintf(&b, " backup")
		} else if s.Weight > 0 {
			fmt.Fprintf(&b, " weight=%d", s.Weight)
		}

		fmt.Fprintf(&b, ";\n")
	}
	if len(state.Servers) == 0 {
		fmt.Fprintf(&b, "    server 127.0.0.1:1 down;\n")
	}

	if state.Keepalive > 0 {
		fmt.Fprintf(&b, "    keepalive %d;\n", state.Keepalive)
	}

	fmt.Fprintf(&b, "}\n")

	return b.String()
}

func renderNginxServer(state *UpstreamState, route NginxRoute, proxyName string) string {
	var b strings.Builder

	if route.SSLCert != "" {
		renderNginxServerBlock(&b, state, route, proxyName, false, route.SSLRedirect)
		b.WriteString("\n")
		renderNginxServerBlock(&b, state, route, proxyName, true, false)
		return b.String()
	}

	renderNginxServerBlock(&b, state, route, proxyName, false, false)
	return b.String()
}

func renderNginxServerBlock(b *strings.Builder, state *UpstreamState, route NginxRoute, proxyName string, ssl, redirectOnly bool) {
	fmt.Fprintf(b, "# Generated by docker-release\n")
	fmt.Fprintf(b, "server {\n")
	if ssl {
		fmt.Fprintf(b, "    listen 443 ssl;\n")
	} else {
		fmt.Fprintf(b, "    listen 80;\n")
	}
	fmt.Fprintf(b, "    server_name %s;\n", normalizeNginxHost(route.Host))
	fmt.Fprintf(b, "    absolute_redirect off;\n")

	if ssl {
		fmt.Fprintf(b, "    ssl_certificate %s;\n", route.SSLCert)
		fmt.Fprintf(b, "    ssl_certificate_key %s;\n", route.SSLKey)
		fmt.Fprintf(b, "    include /etc/docker-release/%s/ssl.d/*.conf;\n", proxyName)
		fmt.Fprintf(b, "    include /etc/docker-release/proxy/ssl.d/*.conf;\n")
	}

	fmt.Fprintf(b, "\n")
	if redirectOnly {
		fmt.Fprintf(b, "    location / {\n")
		fmt.Fprintf(b, "        return 308 https://$host$request_uri;\n")
		fmt.Fprintf(b, "    }\n")
		fmt.Fprintf(b, "}\n")
		return
	}

	for _, line := range strings.Split(strings.TrimSuffix(renderNginxLocation(state, route, proxyName), "\n"), "\n") {
		fmt.Fprintf(b, "    %s\n", line)
	}
	fmt.Fprintf(b, "    include /etc/docker-release/%s/server.d/*.conf;\n", proxyName)
	fmt.Fprintf(b, "    include /etc/docker-release/proxy/server.d/*.conf;\n")
	if ssl {
		fmt.Fprintf(b, "    include /etc/docker-release/%s/https.d/*.conf;\n", proxyName)
		fmt.Fprintf(b, "    include /etc/docker-release/proxy/https.d/*.conf;\n")
	}
	fmt.Fprintf(b, "}\n")
}

func renderNginxLocation(state *UpstreamState, route NginxRoute, proxyName string) string {
	var b strings.Builder
	path := route.Path
	if path == "" {
		path = "/"
	}
	drain := drainsBeforeReload(proxyName)

	fmt.Fprintf(&b, "# Generated by docker-release\n")
	fmt.Fprintf(&b, "location %s {\n", path)
	writeNginxProxySettings(&b, state.ResolveUpstreamName()+"_upstream/")
	if drain {
		fmt.Fprintf(&b, "    if (-f %s) {\n", drainFlagPath(proxyName))
		fmt.Fprintf(&b, "        rewrite ^ %s$uri last;\n", drainLocationPrefix)
		fmt.Fprintf(&b, "    }\n")
	}
	fmt.Fprintf(&b, "}\n")
	if drain {
		// The same route with keep-alive off, used while the proxy is about to reload.
		drainPath := drainLocationPrefix + path
		fmt.Fprintf(&b, "location ^~ %s {\n", drainPath)
		fmt.Fprintf(&b, "    internal;\n")
		fmt.Fprintf(&b, "    keepalive_timeout 0;\n")
		fmt.Fprintf(&b, "    rewrite ^%s(.*)$ /$1 break;\n", strings.ReplaceAll(drainPath, ".", `\.`))
		writeNginxProxySettings(&b, state.ResolveUpstreamName()+"_upstream")
		fmt.Fprintf(&b, "}\n")
	}

	return b.String()
}

func writeNginxProxySettings(b *strings.Builder, target string) {
	fmt.Fprintf(b, "    proxy_set_header Host $host;\n")
	fmt.Fprintf(b, "    proxy_set_header X-Real-IP $remote_addr;\n")
	fmt.Fprintf(b, "    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n")
	fmt.Fprintf(b, "    proxy_set_header X-Forwarded-Proto $scheme;\n")
	fmt.Fprintf(b, "    proxy_http_version 1.1;\n")
	fmt.Fprintf(b, "    proxy_set_header Connection \"\";\n")
	fmt.Fprintf(b, "    proxy_pass http://%s;\n", target)
}

// drainLocationPrefix starts the internal locations that answer with `Connection: close`.
const drainLocationPrefix = "/.dr-drain"

// drainsBeforeReload reports whether a proxy closes idle kept-alive connections on reload
// without warning. Angie answers the next request with `Connection: close` instead.
func drainsBeforeReload(proxyName string) bool {
	return proxyName == "nginx"
}

// drainFlagPath is a file the bundled proxy's locations check; see askClientsToReconnect.
func drainFlagPath(name string) string {
	return "/run/docker-release/" + name + ".draining"
}

func normalizeNginxHost(host string) string {
	return strings.Join(strings.FieldsFunc(host, func(r rune) bool { return r == ',' }), " ")
}
