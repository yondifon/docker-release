package provider

import (
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"syscall"
	"time"

	"github.com/malico/docker-release/internal/health"
)

func (p *NginxProvider) lockConfigs(ctx context.Context) (func(), error) {
	if err := os.MkdirAll(p.configDir, 0o755); err != nil {
		return nil, err
	}
	f, err := os.OpenFile(filepath.Join(p.configDir, ".nginx.lock"), os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return nil, err
	}
	ticker := time.NewTicker(20 * time.Millisecond)
	defer ticker.Stop()
	for {
		err = syscall.Flock(int(f.Fd()), syscall.LOCK_EX|syscall.LOCK_NB)
		if err == nil {
			return func() { _ = f.Close() }, nil
		}
		if !errors.Is(err, syscall.EWOULDBLOCK) {
			_ = f.Close()
			return nil, err
		}
		select {
		case <-ctx.Done():
			_ = f.Close()
			return nil, ctx.Err()
		case <-ticker.C:
		}
	}
}

func writeNginxFile(path string, data []byte) error {
	if data == nil {
		err := os.Remove(path)
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".nginx-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if err := f.Chmod(0o644); err != nil {
		_ = f.Close()
		return err
	}
	_, writeErr := f.Write(data)
	if err := errors.Join(writeErr, f.Close()); err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}

func (p *NginxProvider) applyConfigs(ctx context.Context, changes map[string][]byte) error {
	unlock, err := p.lockConfigs(ctx)
	if err != nil {
		return err
	}
	defer unlock()
	return p.applyConfigsLocked(ctx, changes)
}

func (p *NginxProvider) applyConfigsLocked(ctx context.Context, changes map[string][]byte) error {
	if err := p.checkRouteConflicts(changes); err != nil {
		return err
	}
	previous, err := snapshotNginxFiles(changes)
	if err != nil {
		return err
	}
	for path := range previous {
		if err := writeNginxFile(path, changes[path]); err != nil {
			return restoreNginxFiles(previous, err)
		}
	}
	if err := p.reload(ctx); err != nil {
		return restoreNginxFiles(previous, err)
	}
	for path := range previous {
		if changes[path] == nil {
			health.ForgetFile(path)
		} else {
			health.RecordFile(path)
		}
	}
	return nil
}

func snapshotNginxFiles(changes map[string][]byte) (map[string][]byte, error) {
	previous := make(map[string][]byte, len(changes))
	for path, data := range changes {
		old, err := os.ReadFile(path)
		if err != nil && !os.IsNotExist(err) {
			return nil, err
		}
		if data == nil && old != nil && !strings.HasPrefix(string(old), "# Generated by docker-release") {
			continue
		}
		if data != nil && old != nil && !strings.HasPrefix(string(old), "# Generated by docker-release") {
			return nil, fmt.Errorf("nginx config %s is not managed by docker-release; move it before deploying", path)
		}
		previous[path] = old
	}
	return previous, nil
}

func restoreNginxFiles(previous map[string][]byte, cause error) error {
	for path, old := range previous {
		if err := writeNginxFile(path, old); err != nil {
			cause = errors.Join(cause, fmt.Errorf("restoring %s: %w", path, err))
		}
	}
	return cause
}

func (p *NginxProvider) checkRouteConflicts(changes map[string][]byte) error {
	hosts := make(map[string]bool)
	for path, data := range changes {
		if strings.HasSuffix(path, ".server") {
			for _, host := range nginxServerNames(data) {
				hosts[host] = true
			}
		}
	}
	if len(hosts) == 0 || p.routeDir == "" {
		return nil
	}
	entries, err := os.ReadDir(p.routeDir)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, entry := range entries {
		path := filepath.Join(p.routeDir, entry.Name())
		if _, changing := changes[path]; changing || entry.IsDir() || !strings.HasSuffix(path, ".server") {
			continue
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		for _, host := range nginxServerNames(data) {
			if hosts[host] {
				return fmt.Errorf("nginx host %q is already used by %s; use a different host or a custom server block", host, path)
			}
		}
	}
	return nil
}

func nginxServerNames(data []byte) []string {
	var hosts []string
	for _, line := range strings.Split(string(data), "\n") {
		fields := strings.Fields(strings.TrimSuffix(strings.TrimSpace(line), ";"))
		if len(fields) > 1 && fields[0] == "server_name" {
			for _, host := range fields[1:] {
				hosts = append(hosts, strings.ToLower(host))
			}
		}
	}
	return hosts
}

func (p *NginxProvider) RemoveStaleConfigs(ctx context.Context, active map[string]bool, canRemove func(string) bool) error {
	unlock, err := p.lockConfigs(ctx)
	if err != nil {
		return err
	}
	defer unlock()
	changes := make(map[string][]byte)
	files, err := p.configFilesByService()
	if err != nil {
		return err
	}
	for name, paths := range files {
		if active[name] || !canRemove(name) {
			continue
		}
		for _, path := range paths {
			changes[path] = nil
		}
	}
	if len(changes) == 0 {
		return nil
	}
	return p.applyConfigsLocked(ctx, changes)
}

func (p *NginxProvider) configFilesByService() (map[string][]string, error) {
	files := make(map[string][]string)
	dirs := map[string][]string{p.configDir: {".conf"}}
	dirs[p.routeDir] = append(dirs[p.routeDir], ".server", ".location")
	for dir, extensions := range dirs {
		if dir == "" {
			continue
		}
		entries, err := os.ReadDir(dir)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return nil, err
		}
		for _, entry := range entries {
			ext := filepath.Ext(entry.Name())
			if entry.IsDir() || !slices.Contains(extensions, ext) {
				continue
			}
			path := filepath.Join(dir, entry.Name())
			data, err := os.ReadFile(path)
			if err != nil {
				return nil, err
			}
			if !strings.HasPrefix(string(data), "# Generated by docker-release") {
				continue
			}
			name := strings.TrimSuffix(entry.Name(), ext)
			files[name] = append(files[name], path)
		}
	}
	return files, nil
}
