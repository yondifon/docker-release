func TestTraefikReleaseWaitsForAppliedConfig(t *testing.T) {
	dir := t.TempDir()
	p := NewTraefikRoutes(dir, NginxRoute{Host: "app.localhost", Path: "/app/"})
	if err := p.GenerateConfig(context.Background(), &UpstreamState{Service: "app", Servers: []Server{{Addr: "127.0.0.1:8080"}}}); err != nil {
		t.Fatal(err)
	}
	var applied atomic.Bool
	var queried atomic.Bool
	api := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		queried.Store(true)
		if !applied.Load() {
			_, _ = w.Write([]byte(`{}`))
			return
		}
		data, err := os.ReadFile(filepath.Join(dir, "app.yml"))
		if err != nil {
			http.Error(w, err.Error(), 500)
			return
		}
		var config struct {
			HTTP map[string]map[string]map[string]any `json:"http"`
		}
		if err := json.Unmarshal([]byte(strings.TrimPrefix(string(data), "# Generated by docker-release\n")), &config); err != nil {
			http.Error(w, err.Error(), 500)
			return
		}
		snapshot := make(map[string]map[string]map[string]any)
		for section, entries := range config.HTTP {
			snapshot[section] = make(map[string]map[string]any)
			for name, entry := range entries {
				entry["status"] = "enabled"
				snapshot[section][name+"@file"] = entry
			}
		}
		_ = json.NewEncoder(w).Encode(snapshot)
	}))
	defer api.Close()
	p.apiURL = api.URL
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
	defer cancel()
	done := make(chan error, 1)
	stopped := make(chan struct{})
	go func() {
		defer close(stopped)
		done <- p.Reload(ctx)
	}()
	defer func() {
		cancel()
		<-stopped
	}()
	deadline := time.After(time.Second)
	for !queried.Load() {
		select {
		case <-deadline:
			t.Fatal("Traefik API was not queried")
		case <-time.After(time.Millisecond):
		}
	}
	select {
	case err := <-done:
		t.Fatalf("reload returned before config was applied: %v", err)
	case <-time.After(150 * time.Millisecond):
	}
	applied.Store(true)
	err := <-done
	if err != nil {
		t.Fatal(err)
	}
}

func TestTraefikRejectedCertificatePreservesRoutes(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "app.yml")
	previous := []byte("# Generated by docker-release\n{}")
	if err := os.WriteFile(path, previous, 0o644); err != nil {
		t.Fatal(err)
	}
	cert := filepath.Join(dir, "cert.pem")
	if err := os.WriteFile(cert, []byte("not a certificate"), 0o644); err != nil {
		t.Fatal(err)
	}
	p := NewTraefikRoutes(dir, NginxRoute{Host: "app.localhost", SSLCert: cert, SSLKey: cert})
	if err := p.GenerateConfig(context.Background(), &UpstreamState{Service: "app"}); err == nil {
		t.Fatal("invalid certificate was accepted")
	}
	got, err := os.ReadFile(path)
	if err != nil || string(got) != string(previous) {
		t.Fatalf("working routes changed: %q, %v", got, err)
	}
}
