package provider

import (
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"syscall"
	"time"

	"github.com/malico/docker-release/internal/health"
)

// Files without `generatedPrefix` are not ours and are never touched.
const (
	generatedPrefix = "# Generated by docker-release"
	generatedHeader = generatedPrefix + "\n"
)

type proxyBootstrapKey struct{}

func WithProxyBootstrap(ctx context.Context) context.Context {
	return context.WithValue(ctx, proxyBootstrapKey{}, true)
}

func bundledProxy(name string) bool {
	return strings.EqualFold(strings.TrimSpace(os.Getenv("DR_BUNDLED_PROXY")), name)
}

// bundledBootstrapping is true when the proxy has not started yet and this is first-time setup.
// Any other deploy before the proxy starts is an error.
func bundledBootstrapping(ctx context.Context, name string) (bool, error) {
	_, err := os.Stat("/run/docker-release/" + name + ".started")
	if err == nil {
		return false, nil
	}
	if !os.IsNotExist(err) {
		return false, err
	}
	if bootstrap, _ := ctx.Value(proxyBootstrapKey{}).(bool); bootstrap {
		return true, nil
	}
	return false, fmt.Errorf("bundled %s is not ready; wait until the container is healthy before deploying", name)
}

// writeConfigFile swaps the file in with a rename, so the proxy never reads a half-written one.
func writeConfigFile(path string, data []byte, what string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("creating config dir: %w", err)
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", what, err)
	}
	if err := os.Rename(tmp, path); err != nil {
		return fmt.Errorf("renaming %s: %w", what, err)
	}
	health.RecordFile(path)
	return nil
}

func lockProxyConfigs(ctx context.Context, dir, name string) (func(), error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	f, err := os.OpenFile(filepath.Join(dir, name), os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return nil, err
	}
	ticker := time.NewTicker(20 * time.Millisecond)
	defer ticker.Stop()
	for {
		err = syscall.Flock(int(f.Fd()), syscall.LOCK_EX|syscall.LOCK_NB)
		if err == nil {
			return func() { _ = f.Close() }, nil
		}
		if !errors.Is(err, syscall.EWOULDBLOCK) {
			_ = f.Close()
			return nil, err
		}
		select {
		case <-ctx.Done():
			_ = f.Close()
			return nil, ctx.Err()
		case <-ticker.C:
		}
	}
}

func writeProxyFile(path string, data []byte) error {
	if data == nil {
		err := os.Remove(path)
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".proxy-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if err := f.Chmod(0o644); err != nil {
		_ = f.Close()
		return err
	}
	_, writeErr := f.Write(data)
	if err := errors.Join(writeErr, f.Close()); err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}

// The caller holds the proxy's file lock through the reload and any restore.
func applyProxyConfigFiles(ctx context.Context, changes map[string][]byte, reload func(context.Context) error) error {
	previous := make(map[string][]byte, len(changes))
	for path, data := range changes {
		old, err := os.ReadFile(path)
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		if old != nil && !strings.HasPrefix(string(old), generatedPrefix) {
			if data == nil {
				continue
			}
			return fmt.Errorf("proxy config %s is not managed by docker-release; move it before deploying", path)
		}
		previous[path] = old
	}
	for path := range previous {
		if err := writeProxyFile(path, changes[path]); err != nil {
			return restoreProxyFiles(previous, err)
		}
	}
	if err := reload(ctx); err != nil {
		return restoreProxyFiles(previous, err)
	}
	for path := range previous {
		if changes[path] == nil {
			health.ForgetFile(path)
		} else {
			health.RecordFile(path)
		}
	}
	return nil
}

func restoreProxyFiles(previous map[string][]byte, cause error) error {
	for path, old := range previous {
		if err := writeProxyFile(path, old); err != nil {
			cause = errors.Join(cause, fmt.Errorf("restoring %s: %w", path, err))
		}
	}
	return cause
}

// staleConfigChanges maps each generated file of an inactive, removable service to nil.
func staleConfigChanges(dirs map[string][]string, active map[string]bool, canRemove func(string) bool) (map[string][]byte, error) {
	files, err := proxyConfigFilesByService(dirs)
	if err != nil {
		return nil, err
	}
	changes := make(map[string][]byte)
	for service, paths := range files {
		if active[service] || !canRemove(service) {
			continue
		}
		for _, path := range paths {
			changes[path] = nil
		}
	}
	return changes, nil
}

func proxyConfigFilesByService(dirs map[string][]string) (map[string][]string, error) {
	files := make(map[string][]string)
	for dir, extensions := range dirs {
		if dir == "" {
			continue
		}
		entries, err := os.ReadDir(dir)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return nil, err
		}
		for _, entry := range entries {
			ext := filepath.Ext(entry.Name())
			if entry.IsDir() || !slices.Contains(extensions, ext) {
				continue
			}
			path := filepath.Join(dir, entry.Name())
			data, err := os.ReadFile(path)
			if err != nil {
				return nil, err
			}
			if !strings.HasPrefix(string(data), generatedPrefix) {
				continue
			}
			name := strings.TrimSuffix(entry.Name(), ext)
			files[name] = append(files[name], path)
		}
	}
	return files, nil
}
