package provider

import (
	"context"
	"fmt"
	"path/filepath"
	"strings"

	"github.com/malico/docker-release/internal/docker"
)

type AngieProvider struct {
	configDir   string
	docker      *docker.Client
	serviceName string
	project     string
	previewHost string // set when the service has a preview host; the upstream file then always holds a `_preview` upstream
}

func NewAngie(configDir string, dockerClient *docker.Client, serviceName, project string) *AngieProvider {
	return &AngieProvider{
		configDir:   configDir,
		docker:      dockerClient,
		serviceName: serviceName,
		project:     project,
	}
}

func NewAngieRoutes(configDir, routeDir string, route NginxRoute, dockerClient *docker.Client, serviceName, project string) *NginxProvider {
	p := NewNginx(configDir, routeDir, route, dockerClient, serviceName, project)
	p.proxyName = "angie"
	return p
}

// GenerateConfig creates an Angie upstream configuration file
func (p *AngieProvider) GenerateConfig(ctx context.Context, state *UpstreamState) error {
	if err := state.Validate(); err != nil {
		return err
	}

	return writeConfigFile(filepath.Join(p.configDir, state.Service+".conf"), []byte(renderUpstreamFile("angie", state, p.previewHost)), "config")
}

func (p *AngieProvider) Reload(ctx context.Context) error {
	ctr, running, err := reloadTarget(ctx, p.docker, p.project, p.serviceName, "angie", false, "angie", "nginx")
	if err != nil {
		return err
	}

	if !running {
		return p.docker.Start(ctx, ctr.ID)
	}

	return p.docker.Exec(ctx, ctr.ID, []string{"angie", "-s", "reload"})
}

// renderAngieUpstream generates the upstream block for Angie
// Angie is a drop-in replacement for nginx, so the syntax is identical
func renderAngieUpstream(state *UpstreamState) string {
	var b strings.Builder

	fmt.Fprintf(&b, "# Generated by docker-release for Angie\n")
	fmt.Fprintf(&b, "upstream %s_upstream {\n", state.ResolveUpstreamName())

	switch state.Affinity {
	case "cookie":
		if state.StickyLearnName != "" {
			zone := state.ResolveUpstreamName() + "_sessions"
			fmt.Fprintf(&b, "    sticky learn create=$upstream_cookie_%s lookup=$cookie_%s zone=%s:1m;\n",
				state.StickyLearnName, state.StickyLearnName, zone)
		} else {
			fmt.Fprintf(&b, "    sticky cookie %s path=/;\n", stickyCookieName(state))
		}
	case "ip":
		fmt.Fprintf(&b, "    ip_hash;\n")
	default:
		fmt.Fprintf(&b, "    least_conn;\n")
	}

	writeNginxServers(&b, state, supportsAngieBackup(state.Affinity), true)

	fmt.Fprintf(&b, "}\n")

	return b.String()
}
