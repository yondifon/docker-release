package provider

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"os"
	"strings"
	"time"
)

func (p *TraefikProvider) applyRoutes(ctx context.Context, changes map[string][]byte) error {
	unlock, err := lockProxyConfigs(ctx, p.configDir, ".traefik.lock")
	if err != nil {
		return err
	}
	defer unlock()
	return p.applyRoutesLocked(ctx, changes)
}

func (p *TraefikProvider) applyRoutesLocked(ctx context.Context, changes map[string][]byte) error {
	bootstrap, _ := ctx.Value(proxyBootstrapKey{}).(bool)
	if bootstrap {
		return applyProxyConfigFiles(ctx, changes, func(context.Context) error { return nil })
	}
	if p.apiURL == "http://127.0.0.1:8080" {
		if _, err := os.Stat("/run/docker-release/traefik.started"); err != nil {
			return fmt.Errorf("bundled Traefik is not ready; wait until the container is healthy before deploying: %w", err)
		}
	}
	err := applyProxyConfigFiles(ctx, changes, p.waitForConfig)
	if err == nil {
		return nil
	}
	// Restored files must also reach Traefik before another deployment can write.
	restoreCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 15*time.Second)
	defer cancel()
	return errors.Join(err, p.waitForConfig(restoreCtx))
}

func (p *TraefikProvider) waitForConfig(ctx context.Context) error {
	ctx, cancel := context.WithTimeout(ctx, 15*time.Second)
	defer cancel()
	ticker := time.NewTicker(50 * time.Millisecond)
	defer ticker.Stop()
	var lastErr error
	for {
		if lastErr = p.configApplied(ctx); lastErr == nil {
			return nil
		}
		select {
		case <-ctx.Done():
			return fmt.Errorf("waiting for Traefik to apply routing config: %w: %v", ctx.Err(), lastErr)
		case <-ticker.C:
		}
	}
}

func TraefikReady(ctx context.Context, configDir string) bool {
	return NewTraefikRoutes(configDir, NginxRoute{}).configApplied(ctx) == nil
}

func (p *TraefikProvider) configApplied(ctx context.Context) error {
	expected, err := traefikConfigNames(p.configDir)
	if err != nil {
		return err
	}
	request, err := http.NewRequestWithContext(ctx, http.MethodGet, p.apiURL+"/api/rawdata", nil)
	if err != nil {
		return err
	}
	client := &http.Client{Timeout: time.Second, Transport: &http.Transport{Proxy: nil}}
	defer client.CloseIdleConnections()
	response, err := client.Do(request)
	if err != nil {
		return err
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return fmt.Errorf("Traefik API returned HTTP %d", response.StatusCode)
	}
	var snapshot map[string]map[string]struct {
		Status string   `json:"status"`
		Errors []string `json:"error"`
	}
	if err := json.NewDecoder(io.LimitReader(response.Body, 16<<20)).Decode(&snapshot); err != nil {
		return err
	}
	for _, section := range []string{"routers", "services", "middlewares"} {
		for name := range expected[section] {
			entry, ok := snapshot[section][name]
			if !ok || entry.Status != "enabled" || len(entry.Errors) > 0 {
				return fmt.Errorf("Traefik %s %s is not enabled: %v", section, name, entry.Errors)
			}
		}
		for name := range snapshot[section] {
			if strings.HasPrefix(name, "dr-") && strings.HasSuffix(name, "@file") && !expected[section][name] {
				return fmt.Errorf("Traefik still has previous %s %s", section, name)
			}
		}
	}
	return nil
}

func traefikConfigNames(dir string) (map[string]map[string]bool, error) {
	expected := map[string]map[string]bool{
		"routers": {}, "services": {}, "middlewares": {},
	}
	files, err := proxyConfigFilesByService(map[string][]string{dir: {".yml"}})
	if err != nil {
		return nil, err
	}
	for _, paths := range files {
		for _, path := range paths {
			config, err := readTraefikHTTPConfig(path)
			if err != nil {
				return nil, err
			}
			for section := range expected {
				for name := range config[section] {
					expected[section][name+"@file"] = true
				}
			}
		}
	}
	return expected, nil
}

func readTraefikHTTPConfig(path string) (traefikHTTPConfig, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var config struct {
		HTTP traefikHTTPConfig `json:"http"`
	}
	data = []byte(strings.TrimPrefix(string(data), "# Generated by docker-release\n"))
	if err := json.Unmarshal(data, &config); err != nil {
		return nil, err
	}
	return config.HTTP, nil
}
