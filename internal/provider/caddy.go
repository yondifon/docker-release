package provider

import (
	"bytes"
	"context"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/malico/docker-release/internal/docker"
)

type CaddyProvider struct {
	configDir   string
	docker      *docker.Client
	serviceName string
	project     string
	bundled     bool
	route       CaddyRoute
	pending     map[string][]byte
	stateFile   string
	adminURL    string
}

func NewCaddy(configDir string, dockerClient *docker.Client, serviceName, project string) *CaddyProvider {
	if configDir == "" {
		configDir = "/shared/caddy-config"
	}

	return &CaddyProvider{
		configDir:   configDir,
		docker:      dockerClient,
		serviceName: serviceName,
		project:     project,
		adminURL:    "http://127.0.0.1:2019",
	}
}

func (p *CaddyProvider) GenerateConfig(ctx context.Context, state *UpstreamState) error {
	if err := state.Validate(); err != nil {
		return err
	}

	if p.bundled {
		return p.generateBundledConfig(state)
	}

	conf := renderCaddyUpstream(state)
	if p.route.PreviewHost != "" {
		conf += renderCaddyPreviewUpstream(state)
	}
	return writeConfigFile(filepath.Join(p.configDir, state.Service+".caddy"), []byte(conf), "config")
}

func (p *CaddyProvider) Reload(ctx context.Context) error {
	if p.bundled {
		unlock, err := lockProxyConfigs(ctx, p.configDir, ".caddy.lock")
		if err != nil {
			return err
		}
		defer unlock()
		routesChanged := false
		for path, data := range p.pending {
			if path == p.stateFile {
				continue
			}
			old, err := os.ReadFile(path)
			if err != nil && !os.IsNotExist(err) {
				return err
			}
			if !bytes.Equal(old, data) {
				routesChanged = true
			}
		}
		return applyProxyConfigFiles(ctx, p.pending, func(ctx context.Context) error {
			if routesChanged {
				if err := p.reload(ctx); err != nil {
					return err
				}
			}
			return p.updateUpstreams(ctx)
		})
	}
	return p.reload(ctx)
}

func (p *CaddyProvider) reload(ctx context.Context) error {
	if bootstrap, err := p.bootstrapping(ctx); bootstrap || err != nil {
		return err
	}
	ctr, running, err := reloadTarget(ctx, p.docker, p.project, p.serviceName, "caddy", true, "caddy")
	if err != nil {
		return err
	}
	if !running {
		return p.docker.Start(ctx, ctr.ID)
	}
	args := []string{"caddy", "reload", "--config", "/etc/caddy/Caddyfile"}
	if p.bundled {
		args = append(args, "--force")
	}
	return p.docker.Exec(ctx, ctr.ID, args)
}

func (p *CaddyProvider) bootstrapping(ctx context.Context) (bool, error) {
	if !p.bundled || !bundledProxy("caddy") {
		return false, nil
	}
	return bundledBootstrapping(ctx, "caddy")
}

func (p *CaddyProvider) updateUpstreams(ctx context.Context) error {
	if bootstrap, err := p.bootstrapping(ctx); bootstrap || err != nil {
		return err
	}
	data := bytes.TrimPrefix(p.pending[p.stateFile], []byte(generatedHeader))
	endpoint := p.adminURL + "/docker_release/upstreams?" + url.Values{"file": {p.stateFile}}.Encode()
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(data))
	if err != nil {
		return err
	}
	req.Header.Set("Content-Type", "application/json")
	client := &http.Client{Timeout: 5 * time.Second, Transport: &http.Transport{Proxy: nil}}
	defer client.CloseIdleConnections()
	resp, err := client.Do(req)
	if err != nil {
		return fmt.Errorf("applying Caddy upstreams: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		body, _ := io.ReadAll(io.LimitReader(resp.Body, 8192))
		return fmt.Errorf("caddy rejected upstreams (HTTP %d): %s", resp.StatusCode, body)
	}
	return nil
}

func renderCaddyUpstream(state *UpstreamState) string {
	return "# Generated by docker-release for Caddy\n" + renderCaddySnippet(state)
}

// renderCaddyPreviewUpstream writes the `<name>_preview_upstream` snippet for the
// preview servers. With none, the snippet answers 404, so an `import` of it
// stays valid.
func renderCaddyPreviewUpstream(state *UpstreamState) string {
	preview := state.previewState()
	for _, s := range preview.Servers {
		if !s.Down && !s.Backup {
			return "\n" + renderCaddySnippet(preview)
		}
	}
	return fmt.Sprintf("\n(%s_upstream) {\n    respond 404\n}\n", preview.ResolveUpstreamName())
}

func renderCaddySnippet(state *UpstreamState) string {
	var b strings.Builder

	name := state.ResolveUpstreamName()

	fmt.Fprintf(&b, "(%s_upstream) {\n", name)

	fmt.Fprintf(&b, "    reverse_proxy")

	var active []Server
	for _, s := range state.Servers {
		if !s.Down && !s.Backup {
			active = append(active, s)
		}
	}

	for _, s := range active {
		fmt.Fprintf(&b, " %s", s.Addr)
	}
	fmt.Fprintf(&b, " {\n")

	hasWeights := false
	for _, s := range active {
		if s.Weight > 0 {
			hasWeights = true
			break
		}
	}

	switch state.Affinity {
	case "cookie":
		fmt.Fprintf(&b, "        lb_policy cookie %s\n", stickyCookieName(state))
	case "ip":
		fmt.Fprintf(&b, "        lb_policy ip_hash\n")
	default:
		if hasWeights {
			fmt.Fprintf(&b, "        lb_policy weighted_round_robin")
			for _, s := range active {
				w := s.Weight
				if w == 0 {
					w = 1
				}
				fmt.Fprintf(&b, " %d", w)
			}
			fmt.Fprintf(&b, "\n")
		} else {
			fmt.Fprintf(&b, "        lb_policy round_robin\n")
		}
	}

	if state.Keepalive > 0 {
		fmt.Fprintf(&b, "        transport http {\n")
		fmt.Fprintf(&b, "            keepalive_idle_conns_per_host %d\n", state.Keepalive)
		fmt.Fprintf(&b, "        }\n")
	}

	fmt.Fprintf(&b, "    }\n")

	fmt.Fprintf(&b, "}\n")

	return b.String()
}
