func TestConfigSyncKeepsLiveRoutesWithProjectQualifiedServiceKeys(t *testing.T) {
	dir := t.TempDir()
	routes := t.TempDir()
	files := []string{filepath.Join(dir, "app.conf"), filepath.Join(routes, "app.server")}
	for _, path := range files {
		if err := os.WriteFile(path, []byte("# Generated by docker-release\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	c := &Controller{project: "stack"}
	err := c.cleanStaleConfigs(context.Background(), map[string]*config.ServiceConfig{
		"stack/app": {Provider: config.ProviderNginx, NginxConfigDir: dir, NginxRouteDir: routes, RouteHost: "app.example.com"},
	})
	if err != nil {
		t.Fatal(err)
	}
	for _, path := range files {
		if _, err := os.Stat(path); err != nil {
			t.Fatalf("live config was removed during a refresh: %s: %v", path, err)
		}
	}
}

func TestCleanupKeepsLiveNonNginxConfigsAndRemovesStaleFiles(t *testing.T) {
	for _, kind := range []config.ProviderType{config.ProviderAngie, config.ProviderCaddy, config.ProviderHAProxy, config.ProviderTraefik} {
		t.Run(string(kind), func(t *testing.T) {
			dir := t.TempDir()
			cfg := &config.ServiceConfig{Provider: kind, AngieConfigDir: dir, CaddyConfigDir: dir, HAProxyConfigDir: dir, TraefikConfigDir: dir}
			ext := map[config.ProviderType]string{config.ProviderAngie: ".conf", config.ProviderCaddy: ".caddy", config.ProviderHAProxy: ".cfg", config.ProviderTraefik: ".yml"}[kind]
			for _, name := range []string{"app", "removed", "custom"} {
				content := "# Generated by docker-release\n"
				if name == "custom" {
					content = "# User config\n"
				}
				if err := os.WriteFile(filepath.Join(dir, name+ext), []byte(content), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			c := &Controller{project: "stack"}
			if err := c.cleanStaleConfigs(context.Background(), map[string]*config.ServiceConfig{"stack/app": cfg}); err != nil {
				t.Fatal(err)
			}
			for _, name := range []string{"app", "custom"} {
				if _, err := os.Stat(filepath.Join(dir, name+ext)); err != nil {
					t.Fatalf("cleanup removed %s config: %v", name, err)
				}
			}
			if _, err := os.Stat(filepath.Join(dir, "removed"+ext)); !os.IsNotExist(err) {
				t.Fatalf("stale config remains: %v", err)
			}
		})
	}
}

func controllerConfigFixture(t *testing.T, snapshot func(int32) []types.Container) (*Controller, *config.ServiceConfig) {
	t.Helper()
	var calls atomic.Int32
	api := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		path := strings.TrimPrefix(r.URL.Path, "/v1.47")
		switch {
		case path == "/containers/json":
			if strings.Contains(r.URL.Query().Get("filters"), "release.enable") {
				_ = json.NewEncoder(w).Encode(snapshot(calls.Add(1)))
			} else {
				_, _ = w.Write([]byte(`[{"Id":"nginx0123456789","Image":"nginx:alpine"}]`))
			}
		case strings.HasPrefix(path, "/containers/") && strings.HasSuffix(path, "/json"):
			addr := "172.18.0.9"
			if strings.Contains(path, "old") {
				addr = "172.18.0.4"
			}
			_, _ = w.Write([]byte(`{"Config":{"ExposedPorts":{"80/tcp":{}}},"State":{"Running":true},"NetworkSettings":{"Networks":{"test":{"IPAddress":"` + addr + `"}}}}`))
		case strings.HasSuffix(path, "/exec"):
			_, _ = w.Write([]byte(`{"Id":"exec"}`))
		case strings.HasSuffix(path, "/start"):
		case path == "/exec/exec/json":
			_, _ = w.Write([]byte(`{"Running":false,"ExitCode":0}`))
		default:
			t.Errorf("unexpected Docker API request: %s", path)
			http.NotFound(w, r)
		}
	}))
	t.Cleanup(api.Close)
	t.Setenv("DOCKER_HOST", api.URL)
	t.Setenv("DOCKER_API_VERSION", "1.47")
	t.Setenv("DR_BUNDLED_PROXY", "")
	client, err := docker.NewClient()
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = client.Close() })
	cfg := &config.ServiceConfig{Provider: config.ProviderNginx, NginxConfigDir: t.TempDir(), NginxRouteDir: t.TempDir(), RouteHost: "app.example.com"}
	c := New(client, state.NewManager(t.TempDir(), "stack"), "stack")
	return c, cfg
}

func TestRefreshDoesNotRestoreContainersReplacedAfterDiscovery(t *testing.T) {
	var labels atomic.Value
	c, cfg := controllerConfigFixture(t, func(call int32) []types.Container {
		id := "new0123456789"
		if call == 1 {
			id = "old0123456789"
		}
		return []types.Container{{ID: id, Labels: labels.Load().(map[string]string)}}
	})
	labels.Store(map[string]string{
		"com.docker.compose.project": "stack", "com.docker.compose.service": "app",
		"release.enable": "true", "release.provider": "nginx",
		"release.nginx.config_dir": cfg.NginxConfigDir, "release.nginx.route_dir": cfg.NginxRouteDir,
		"release.nginx.host": cfg.RouteHost,
	})
	c.refreshServiceConfig(context.Background(), serviceKey{project: "stack", service: "app"})
	data, err := os.ReadFile(filepath.Join(cfg.NginxConfigDir, "app.conf"))
	if err != nil || !strings.Contains(string(data), "172.18.0.9:80") || strings.Contains(string(data), "172.18.0.4:80") {
		t.Fatalf("refresh restored an old container after replacement: %s, %v", data, err)
	}
}

func TestCleanupDoesNotDeleteServiceStartedAfterDiscovery(t *testing.T) {
	c, cfg := controllerConfigFixture(t, func(int32) []types.Container {
		return []types.Container{{ID: "new0123456789", Labels: map[string]string{"com.docker.compose.service": "app"}}}
	})
	c.nginxConfigs = map[nginxConfigDirs]*config.ServiceConfig{{cfg.NginxConfigDir, cfg.NginxRouteDir}: cfg}
	paths := []string{filepath.Join(cfg.NginxConfigDir, "app.conf"), filepath.Join(cfg.NginxRouteDir, "app.server")}
	for _, path := range paths {
		if err := os.WriteFile(path, []byte("# Generated by docker-release\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := c.cleanStaleConfigs(context.Background(), nil); err != nil {
		t.Fatal(err)
	}
	for _, path := range paths {
		if _, err := os.Stat(path); err != nil {
			t.Fatalf("cleanup deleted a newly started service's config: %v", err)
		}
	}
}

func TestCleanupPreservesUnmanagedConfigWithNonServiceFilename(t *testing.T) {
	c, cfg := controllerConfigFixture(t, func(int32) []types.Container { return nil })
	c.nginxConfigs = map[nginxConfigDirs]*config.ServiceConfig{{cfg.NginxConfigDir, cfg.NginxRouteDir}: cfg}
	path := filepath.Join(cfg.NginxConfigDir, "custom server.conf")
	content := "# Custom nginx config\n"
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := c.cleanStaleConfigs(context.Background(), nil); err != nil {
		t.Fatalf("cleanup treated an unmanaged file as a service: %v", err)
	}
	data, err := os.ReadFile(path)
	if err != nil || string(data) != content {
		t.Fatalf("cleanup changed unmanaged config: %s, %v", data, err)
	}
}
