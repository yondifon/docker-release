package runtime

import (
	"encoding/json"
	"fmt"
	"io"
	"net"
	"net/http"
	"os"
	"strconv"
	"strings"
	"sync"
	"sync/atomic"

	"github.com/caddyserver/caddy/v2"
	"github.com/caddyserver/caddy/v2/caddyconfig/caddyfile"
	"github.com/caddyserver/caddy/v2/modules/caddyhttp/reverseproxy"
)

const fileHeader = "# Generated by docker-release\n"

type Source struct {
	File string `json:"file"`
	pool *pool
}

type pool struct {
	addresses atomic.Pointer[[]string]
	users     int
}

var pools = struct {
	sync.Mutex
	files map[string]*pool
}{files: make(map[string]*pool)}

func init() {
	caddy.RegisterModule(Source{})
	caddy.RegisterModule(admin{})
}

func (Source) CaddyModule() caddy.ModuleInfo {
	return caddy.ModuleInfo{ID: "http.reverse_proxy.upstreams.docker_release", New: func() caddy.Module { return new(Source) }}
}

func (s *Source) UnmarshalCaddyfile(d *caddyfile.Dispenser) error {
	for d.Next() {
		if !d.AllArgs(&s.File) {
			return d.ArgErr()
		}
	}
	return nil
}

func (s *Source) Provision(_ caddy.Context) error {
	data, err := os.ReadFile(s.File)
	if err != nil {
		return err
	}
	addresses, err := decodeAddresses(strings.TrimPrefix(string(data), fileHeader))
	if err != nil {
		return err
	}
	pools.Lock()
	defer pools.Unlock()
	s.pool = pools.files[s.File]
	if s.pool == nil {
		s.pool = new(pool)
		s.pool.addresses.Store(&addresses)
		pools.files[s.File] = s.pool
	}
	s.pool.users++
	return nil
}

func (s *Source) Cleanup() error {
	if s.pool == nil {
		return nil
	}
	pools.Lock()
	defer pools.Unlock()
	s.pool.users--
	if s.pool.users == 0 {
		delete(pools.files, s.File)
	}
	return nil
}

func (s *Source) GetUpstreams(_ *http.Request) ([]*reverseproxy.Upstream, error) {
	addresses := *s.pool.addresses.Load()
	upstreams := make([]*reverseproxy.Upstream, len(addresses))
	for i, address := range addresses {
		upstreams[i] = &reverseproxy.Upstream{Dial: address}
	}
	return upstreams, nil
}

type admin struct{}

func (admin) CaddyModule() caddy.ModuleInfo {
	return caddy.ModuleInfo{ID: "admin.api.docker_release", New: func() caddy.Module { return new(admin) }}
}

func (admin) Routes() []caddy.AdminRoute {
	return []caddy.AdminRoute{{Pattern: "/docker_release/upstreams", Handler: caddy.AdminHandlerFunc(updateUpstreams)}}
}

func updateUpstreams(w http.ResponseWriter, r *http.Request) error {
	if r.Method != http.MethodPost {
		return caddy.APIError{HTTPStatus: http.StatusMethodNotAllowed, Err: fmt.Errorf("use POST")}
	}
	data, err := io.ReadAll(http.MaxBytesReader(w, r.Body, 1<<20))
	if err != nil {
		return caddy.APIError{HTTPStatus: http.StatusBadRequest, Err: err}
	}
	addresses, err := decodeAddresses(string(data))
	if err != nil {
		return caddy.APIError{HTTPStatus: http.StatusBadRequest, Err: err}
	}
	pools.Lock()
	defer pools.Unlock()
	p := pools.files[r.URL.Query().Get("file")]
	if p == nil {
		return caddy.APIError{HTTPStatus: http.StatusNotFound, Err: fmt.Errorf("upstream file is not configured")}
	}
	p.addresses.Store(&addresses)
	w.WriteHeader(http.StatusOK)
	return nil
}

func decodeAddresses(data string) ([]string, error) {
	var addresses []string
	if err := json.Unmarshal([]byte(data), &addresses); err != nil {
		return nil, err
	}
	for _, address := range addresses {
		host, port, err := net.SplitHostPort(address)
		if err != nil || host == "" {
			return nil, fmt.Errorf("invalid upstream address %q", address)
		}
		number, err := strconv.Atoi(port)
		if err != nil || number < 1 || number > 65535 {
			return nil, fmt.Errorf("invalid upstream port %q", port)
		}
	}
	return addresses, nil
}
